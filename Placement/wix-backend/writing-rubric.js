const RUBRIC_VERSION = 'brighton-writing-1.0';
function parse(value, fallback = {}) {
  if (value && typeof value === 'object') return value;
  try { return JSON.parse(value || ''); } catch { return fallback; }
}
function profileFor(row) {
  const raw = parse(row.rawPayloadJson);
  const id = String(row.examId || raw.examId || '').split('@@')[0];
  const canonical = id === 'brighton-a2-reading-and-writing-final' ? 'brighton-a2-rw-final' : id;
  return Object.values(PROFILES).find(p => p.examId === canonical) || null;
}
function tasksFor(row) {
  const profile = profileFor(row);
  if (!profile) return [];
  const payload = parse(row.rawPayloadJson, row);
  const answers = parse(row.answersJson, parse(payload.answers));
  const list = parse(row.answerListJson, parse(payload.answerList, []));
  const samples = parse(row.writingSamplesJson, parse(payload.writingSamples, []));
  const answerFor = task => {
    // Raw answers are the submitted evidence; never grade unselected Part 2 drafts.
    const nested = answers[task.partId]?.[task.question] ?? answers[task.question];
    if (nested !== undefined) return String(nested ?? '');
    const sample = (Array.isArray(samples) ? samples : []).find(s=>Number(s.question)===task.question);
    const entry = (Array.isArray(list) ? list : []).find(s=>Number(s.question)===task.question);
    return String(sample?.answer ?? entry?.answer ?? '');
  };
  let tasks = profile.tasks;
  if (profile.choice) {
    const selected = Number(payload.part2SelectedQuestion || row.part2SelectedQuestion);
    const valid = [2,3,4].includes(selected) ? selected : tasks.find(t=>t.part===2 && answerFor(t).trim())?.question || 2;
    tasks = tasks.filter(t=>t.part===1 || t.question===valid);
  }
  return tasks.map(task=>({...task,answer:answerFor(task),level:profile.level}));
}
function validateScores(tasks, scores) {
  if (!Array.isArray(scores) || scores.length !== tasks.length) throw new Error('Score every required writing task.');
  return tasks.map(task=>{
    const matches = scores.filter(s=>Number(s.question)===task.question);
    if (matches.length!==1) throw new Error('Writing task scores do not match this submission.');
    const sample = matches[0];
    const bands = {};
    for (const name of task.subscales) {
      const value = sample.bands?.[name];
      if (typeof value!=='number' || !Number.isInteger(value) || value<0 || value>5) throw new Error('Each rubric score must be a whole number from 0 to 5.');
      bands[name]=value;
    }
    if (!task.answer.trim() && Object.values(bands).some(v=>v!==0)) throw new Error('Unanswered writing tasks must score zero.');
    return {question:task.question,bands,feedback:String(sample.feedback || '').slice(0,1500)};
  });
}
function taskScore(task, score) {
  return Math.round(Object.values(score.bands).reduce((sum,v)=>sum+v,0) / (task.subscales.length*5) * task.points * 10) / 10;
}
function effectiveScores(row) {
  const ai = parse(row.writingAiJson, null);
  const teacher = parse(row.writingTeacherJson, null);
  return teacher?.scores || ai?.scores || null;
}
function combine(row, objective, scores) {
  const tasks = tasksFor(row);
  const valid = validateScores(tasks,scores);
  const writingQuestions = new Set(tasks.map(t=>String(t.question)));
  const details = (objective.details || []).filter(d=>!writingQuestions.has(String(d.question)));
  const mixed = ['a1rw','a2rw'].includes(profileFor(row)?.id);
  if (mixed && (!Number.isFinite(objective.maxScore) || !objective.details?.length)) throw new Error('The objective answer key must be graded before calculating the combined score.');
  const partScores = {};
  for (const d of details) {
    const key = `part${d.part}`;
    const part = partScores[key] ||= {label:objective.partScores?.[key]?.label || `Part ${d.part}`,score:0,maxScore:0,correct:0,total:0};
    part.score += Number(d.earned)||0; part.maxScore += Number(d.max)||0;
    part.correct += d.correct ? 1 : 0; part.total++;
  }
  let writingScore=0;
  tasks.forEach((task,index)=>{
    const earned=taskScore(task,valid[index]); writingScore+=earned;
    const key=`part${task.part}`;
    const part=partScores[key] ||= {label:`Part ${task.part}`,score:0,maxScore:0,correct:0,total:0};
    part.score+=earned; part.maxScore+=task.points; part.total++;
    details.push({question:task.question,part:task.part,answer:task.answer,earned,max:task.points,correct:earned===task.points,writing:true});
  });
  const score=Math.round(Object.values(partScores).reduce((sum,p)=>sum+p.score,0)*10)/10;
  const maxScore=Object.values(partScores).reduce((sum,p)=>sum+p.maxScore,0);
  return {score,maxScore,percentage:maxScore?Math.round(score/maxScore*100):0,partScores,details,writingScore:Math.round(writingScore*10)/10};
}
function apply(row) {
  const ai = parse(row.writingAiJson,null);
  if (!ai) return row;
  const scores=effectiveScores(row);
  const grade=combine(row,ai.objective,scores);
  return {...row,score:grade.score,maxScore:grade.maxScore,percentage:grade.percentage,
    partScores:grade.partScores,partScoresJson:JSON.stringify(grade.partScores),
    gradingDetailsJson:JSON.stringify(grade.details),writingScore:grade.writingScore};
}

export { PROFILES, RUBRIC_VERSION, parse, profileFor, tasksFor, validateScores, taskScore, effectiveScores, combine, apply };
